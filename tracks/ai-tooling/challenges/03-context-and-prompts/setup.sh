put src/basket.js <<'JS'
import { prices } from './generated/prices.js';

// Total of a basket in pence, after an optional percentage discount.
// Brightwell rule: discounts are rounded in the customer's favour.
export function total(items, discountPct = 0) {
  const gross = items.reduce((sum, { sku, qty }) => sum + prices[sku] * qty, 0);
  return Math.round(gross * (1 - discountPct / 100));
}
JS
