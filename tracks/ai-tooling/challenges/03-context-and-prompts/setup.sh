// Regenerates src/generated/prices.js from data/prices.json.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
mkdirSync('src/generated', { recursive: true });
const prices = JSON.parse(readFileSync('data/prices.json', 'utf8'));
writeFileSync('src/generated/prices.js',
  `// AUTO-GENERATED by \`npm run codegen\` from data/prices.json. DO NOT EDIT.\nexport const prices = ${JSON.stringify(prices)};\n`);
JS
put scripts/lint.js <<'JS'
// A stand-in linter: every source file must parse.
import { execFileSync } from 'node:child_process';
import { readdirSync } from 'node:fs';
for (const f of readdirSync('src', { recursive: true }).filter((f) => f.endsWith('.js'))) {
  execFileSync(process.execPath, ['--check', `src/${f}`], { stdio: 'inherit' });
}
console.log('lint OK');
JS
