test('applies a 10% discount', () => assert.equal(total([{ sku: 'RUG-02', qty: 1 }], 10), 4499));
test("rounds discounts in the customer's favour", () => assert.equal(total([{ sku: 'LAMP-01', qty: 1 }], 10), 1795));
