#!/usr/bin/env bash
source "$REPO_ROOT/lib/sandbox.sh"
source "$REPO_ROOT/lib/node.sh"
need node "Install Node.js 20+ (https://nodejs.org or nvm)."
need npm

sandbox_reset

# The shop app uses ONE small function from @demo/utils, but the bundle ships
# the whole library, including a heavy chart engine. Two things block tree
# shaking: the code is CommonJS, and the library doesn't declare it's free of
# side effects.
put .gitignore <<'TXT'
node_modules/
dist/
TXT
put package.json <<'JSON'
{
  "name": "demo-monorepo",
  "private": true,
  "workspaces": ["packages/*", "apps/*"],
  "scripts": {
    "build": "esbuild apps/shop/index.js --bundle --platform=node --format=esm --outfile=dist/shop.mjs"
  },
  "devDependencies": {
    "esbuild": "^0.28.0"
  }
}
JSON
put packages/utils/package.json <<'JSON'
{
  "name": "@demo/utils",
  "version": "1.0.0",
  "main": "index.js"
}
JSON
put packages/utils/index.js <<'JS'
const { formatPrice } = require('./format');
const { renderChart } = require('./chart');

module.exports = { formatPrice, renderChart };
JS
put packages/utils/format.js <<'JS'
function formatPrice(pence) {
  return `£${(pence / 100).toFixed(2)}`;
}

module.exports = { formatPrice };
JS
put packages/utils/chart.js <<'JS'
// Imagine 500 KB of charting library here. Do not edit this file —
// the goal is to stop shipping it, not to delete it.
globalThis.chartEngines = ['HEAVY_CHART_ENGINE'];

function renderChart(data) {
  return `HEAVY_CHART_ENGINE rendering ${data.length} points`;
}

module.exports = { renderChart };
JS
put apps/shop/package.json <<'JSON'
{
  "name": "@demo/shop",
  "version": "1.0.0",
  "private": true,
  "dependencies": {
    "@demo/utils": "1.0.0"
  }
}
JSON
put apps/shop/index.js <<'JS'
const utils = require('@demo/utils');

console.log(utils.formatPrice(1999));
JS
sb_commit_all "Shop app bundling all of @demo/utils"
